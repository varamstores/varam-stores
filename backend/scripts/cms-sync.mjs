// Syncs backend/cms/pages/*.mjs into the CMS tables and generates src/cms/content.gen.ts.
//
//   npm run cms:sync                 structure + values for NEW entries only (admin edits are kept)
//   npm run cms:sync -- --dry-run    validate definitions and regenerate types, touch nothing
//   npm run cms:sync -- --reset=a.b.c,d.e.f   also overwrite the value of these entries
//   npm run cms:sync -- --prune      delete pages/sections/entries that are no longer defined
//
// Structure that admins can edit (section order, enabled, desktop/mobile visibility, SEO,
// page published) is written on insert only.
import { readdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { BACKEND_DIR, REPO_DIR } from './lib/env.mjs';
import { connect, describePgError } from './lib/db.mjs';
import { ICONS } from '../cms/define.mjs';

const args = process.argv.slice(2);
const DRY = args.includes('--dry-run');
const PRUNE = args.includes('--prune');
const RESET = new Set((args.find((a) => a.startsWith('--reset=')) ?? '--reset=').slice(8).split(',').filter(Boolean));

// ── load + validate ────────────────────────────────────────────────────────────────────────────
const PAGES_DIR = path.join(BACKEND_DIR, 'cms', 'pages');
const files = readdirSync(PAGES_DIR).filter((f) => f.endsWith('.mjs')).sort();
const pages = [];
for (const file of files) {
  const mod = await import(pathToFileURL(path.join(PAGES_DIR, file)).href);
  // a file may define one page or several (e.g. all static pages)
  pages.push(...(Array.isArray(mod.default) ? mod.default : [mod.default]));
}

const errors = [];
const pageRows = [], sectionRows = [], entryRows = [];
const seenPages = new Set(), seenEntries = new Set();
const KEY = /^[a-z][a-z0-9_]*$/;
pages.forEach((pg, pi) => {
  if (!KEY.test(pg.key)) errors.push(`page key "${pg.key}" must be snake_case`);
  if (seenPages.has(pg.key)) errors.push(`duplicate page "${pg.key}"`);
  seenPages.add(pg.key);
  if (pg.seoTitle && pg.seoTitle.length > 70) errors.push(`${pg.key}: SEO title over 70 characters`);
  if (pg.seoDescription && pg.seoDescription.length > 170) errors.push(`${pg.key}: SEO description over 170 characters`);
  pageRows.push({ key: pg.key, label: pg.label, route: pg.route, kind: pg.kind, help: pg.help, position: pi * 10,
    seo_title: pg.seoTitle, seo_description: pg.seoDescription, seo_image: pg.seoImage, is_published: pg.isPublished });
  const seenSections = new Set();
  pg.sections.forEach((sc, si) => {
    if (!KEY.test(sc.key)) errors.push(`${pg.key}: section key "${sc.key}" must be snake_case`);
    if (seenSections.has(sc.key)) errors.push(`${pg.key}: duplicate section "${sc.key}"`);
    seenSections.add(sc.key);
    sectionRows.push({ page_key: pg.key, key: sc.key, label: sc.label, help: sc.help, position: si * 10,
      is_enabled: sc.enabled, visible_desktop: sc.desktop, visible_mobile: sc.mobile, is_reorderable: sc.reorderable });
    sc.entries.forEach((e, ei) => {
      const key = `${pg.key}.${sc.key}.${e.name}`;
      if (!/^[a-z0-9_]+$/.test(e.name)) errors.push(`${key}: entry name must be snake_case`);
      if (seenEntries.has(key)) errors.push(`duplicate entry "${key}"`);
      seenEntries.add(key);
      if (e.value === undefined) errors.push(`${key}: missing initial value`);
      if ((e.kind === 'text' || e.kind === 'richtext') && typeof e.value !== 'string') errors.push(`${key}: value must be a string`);
      if (e.maxLength && typeof e.value === 'string' && e.value.length > e.maxLength) errors.push(`${key}: value longer than max ${e.maxLength}`);
      entryRows.push({ key, page_key: pg.key, section_key: sc.key, kind: e.kind, value: e.value, label: e.label,
        help: e.help, item_schema: e.itemSchema, max_length: e.maxLength, position: ei * 10, ts: e.ts });
    });
  });
});
for (const k of RESET) if (!seenEntries.has(k)) errors.push(`--reset: unknown entry "${k}"`);
if (errors.length) {
  console.error(`✗ ${errors.length} problem(s) in CMS definitions:\n  ` + errors.join('\n  '));
  process.exit(1);
}

// ── generate TypeScript ────────────────────────────────────────────────────────────────────────
const q = (s) => `'${s.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
const ts = [
  '// GENERATED by backend/scripts/cms-sync.mjs from backend/cms/pages/*.mjs. Do not edit by hand.',
  '/* eslint-disable */',
  "import type { CmsImage, CmsLink } from './types';",
  '',
  `export const CMS_ICON_NAMES = [${ICONS.map(q).join(', ')}] as const;`,
  'export type CmsIconName = (typeof CMS_ICON_NAMES)[number];',
  '',
  `export type CmsPageKey = ${pageRows.map((p) => q(p.key)).join(' | ')};`,
  `export type CmsSectionKey =\n  | ${sectionRows.map((s) => q(`${s.page_key}.${s.key}`)).join('\n  | ')};`,
  '',
  'export interface CmsEntries {',
  ...entryRows.map((e) => `  ${q(e.key)}: ${e.ts};`),
  '}',
  '',
  "export type CmsKind = 'text' | 'richtext' | 'image' | 'link' | 'list' | 'number' | 'boolean' | 'color' | 'json';",
  '/** Kind of every entry, used to return a safe empty value if an entry is missing from the bundle. */',
  'export const CMS_KINDS: Record<keyof CmsEntries, CmsKind> = {',
  ...entryRows.map((e) => `  ${q(e.key)}: ${q(e.kind)},`),
  '};',
  '',
];
const tsPath = path.join(REPO_DIR, 'src', 'cms', 'content.gen.ts');
writeFileSync(tsPath, ts.join('\n'));
console.log(`✓ ${pageRows.length} pages, ${sectionRows.length} sections, ${entryRows.length} entries · types → src/cms/content.gen.ts`);
if (DRY) process.exit(0);

// ── write to Postgres (one transaction, batched) ──────────────────────────────────────────────
const client = await connect();
let sql = '';
try {
  await client.query('begin');
  const run = async (text, params) => { sql = text; return client.query(text, params); };

  const pg = await run(`
    insert into app.cms_pages (key, label, route, kind, help, position, seo_title, seo_description, seo_image, is_published)
    select x.key, x.label, x.route, x.kind, x.help, x.position, x.seo_title, x.seo_description, x.seo_image, x.is_published
      from jsonb_to_recordset($1::jsonb) as x(key text, label text, route text, kind text, help text, position int,
           seo_title text, seo_description text, seo_image jsonb, is_published boolean)
    on conflict (key) do update set label = excluded.label, route = excluded.route, kind = excluded.kind,
      help = excluded.help, position = excluded.position
    where (app.cms_pages.label, app.cms_pages.route, app.cms_pages.kind, app.cms_pages.help, app.cms_pages.position)
      is distinct from (excluded.label, excluded.route, excluded.kind, excluded.help, excluded.position)
    returning (xmax = 0) as inserted`, [JSON.stringify(pageRows)]);

  const sc = await run(`
    insert into app.cms_sections (page_key, key, label, help, position, is_enabled, visible_desktop, visible_mobile, is_reorderable)
    select x.page_key, x.key, x.label, x.help, x.position, x.is_enabled, x.visible_desktop, x.visible_mobile, x.is_reorderable
      from jsonb_to_recordset($1::jsonb) as x(page_key text, key text, label text, help text, position int,
           is_enabled boolean, visible_desktop boolean, visible_mobile boolean, is_reorderable boolean)
    on conflict (page_key, key) do update set label = excluded.label, help = excluded.help, is_reorderable = excluded.is_reorderable
    where (app.cms_sections.label, app.cms_sections.help, app.cms_sections.is_reorderable)
      is distinct from (excluded.label, excluded.help, excluded.is_reorderable)
    returning (xmax = 0) as inserted`, [JSON.stringify(sectionRows)]);

  const en = await run(`
    insert into app.cms_entries (key, locale, page_key, section_key, kind, value, label, help, item_schema, max_length, position)
    select x.key, 'en-GB', x.page_key, x.section_key, x.kind, x.value, x.label, x.help, x.item_schema, x.max_length, x.position
      from jsonb_to_recordset($1::jsonb) as x(key text, page_key text, section_key text, kind text, value jsonb, label text,
           help text, item_schema jsonb, max_length int, position int)
    on conflict (key, locale) do update set page_key = excluded.page_key, section_key = excluded.section_key,
      kind = excluded.kind, label = excluded.label, help = excluded.help, item_schema = excluded.item_schema,
      max_length = excluded.max_length, position = excluded.position
    where (app.cms_entries.page_key, app.cms_entries.section_key, app.cms_entries.kind, app.cms_entries.label,
           app.cms_entries.help, app.cms_entries.item_schema, app.cms_entries.max_length, app.cms_entries.position)
      is distinct from (excluded.page_key, excluded.section_key, excluded.kind, excluded.label,
           excluded.help, excluded.item_schema, excluded.max_length, excluded.position)
    returning (xmax = 0) as inserted`, [JSON.stringify(entryRows.map(({ ts: _ts, ...r }) => r))]);

  let reset = 0;
  if (RESET.size) {
    const r = await run(`
      update app.cms_entries e set value = x.value
        from jsonb_to_recordset($1::jsonb) as x(key text, value jsonb)
       where e.key = x.key and e.locale = 'en-GB' and e.value is distinct from x.value`,
      [JSON.stringify(entryRows.filter((e) => RESET.has(e.key)).map((e) => ({ key: e.key, value: e.value })))]);
    reset = r.rowCount;
  }

  // Orphans: defined in the DB but no longer in code.
  const orphans = await run(`
    select 'entry' as what, key from app.cms_entries where not (key = any($1::text[]))
    union all select 'section', page_key || '.' || key from app.cms_sections where not (page_key || '.' || key = any($2::text[]))
    union all select 'page', key from app.cms_pages where not (key = any($3::text[]))
    order by 1, 2`,
    [[...seenEntries], sectionRows.map((s) => `${s.page_key}.${s.key}`), [...seenPages]]);
  if (orphans.rowCount) {
    if (PRUNE) {
      await run(`delete from app.cms_entries where not (key = any($1::text[]))`, [[...seenEntries]]);
      await run(`delete from app.cms_sections where not (page_key || '.' || key = any($1::text[]))`, [sectionRows.map((s) => `${s.page_key}.${s.key}`)]);
      await run(`delete from app.cms_pages where not (key = any($1::text[]))`, [[...seenPages]]);
      console.log(`  pruned ${orphans.rowCount} item(s) no longer defined`);
    } else {
      console.log(`  ⚠ ${orphans.rowCount} item(s) in the DB are no longer defined (run with --prune to delete):`);
      for (const o of orphans.rows.slice(0, 30)) console.log(`    ${o.what} ${o.key}`);
    }
  }

  const count = (r) => ({ inserted: r.rows.filter((x) => x.inserted).length, updated: r.rows.filter((x) => !x.inserted).length });
  const summary = { pages: count(pg), sections: count(sc), entries: count(en), valuesReset: reset };
  await run(`select app.audit('cms.sync', 'cms', null, $1::jsonb)`, [JSON.stringify(summary)]);
  await client.query('commit');
  for (const [k, v] of Object.entries(summary)) {
    console.log(typeof v === 'number' ? `  ${k}: ${v}` : `  ${k}: ${v.inserted} new, ${v.updated} updated`);
  }
} catch (err) {
  await client.query('rollback').catch(() => {});
  console.error('✗ CMS sync failed, nothing was changed.\n' + describePgError(err, sql));
  process.exitCode = 1;
} finally {
  await client.end();
}
